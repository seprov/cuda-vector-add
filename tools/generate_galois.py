"""Run the external IrGL compiler and remove unused graph-app boilerplate.

The compiler generates the kernel body, including its GPU loop mapping.
Keep the raw output and adaptation diff so that mapping can be inspected.
"""
import argparse
import difflib
import hashlib
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--compiler", type=Path, required=True,
                        help="Path to the Python 3 galois-compiler checkout")
    args = parser.parse_args()
    compiler = args.compiler.resolve()
    if not (compiler / "src/ggc").is_file():
        parser.error("--compiler must point to a checkout containing src/ggc")

    root = Path(__file__).resolve().parents[1]
    source = root / "kernels/galois_generate_then_add.py"
    with tempfile.TemporaryDirectory(prefix="galois-generate-then-add-") as temporary:
        raw_path = Path(temporary) / "kernel.cu"
        command = [sys.executable, str(compiler / "src/ggc"), str(source),
                   "--cuda-worklist", "basic", "--cuda-graph", "basic",
                   "--dis-opt", "all", "-o", str(raw_path)]
        subprocess.run(command, cwd=temporary, check=True,
                       env=dict(os.environ, PYTHONHASHSEED="0"))
        raw = raw_path.read_text()

    replacements = {
        '#include "gg.h"': '#include <cstddef>\n#include <cuda_runtime.h>',
        'void kernel_sizing(CSRGraph &, dim3 &, dim3 &);\n': '',
        '#define TB_SIZE 256\n': '',
        '  const unsigned __kernel_tb_size = TB_SIZE;\n': '',
    }
    adapted = raw
    for before, after in replacements.items():
        if adapted.count(before) != 1:
            raise RuntimeError("Unexpected IrGL output: " + before)
        adapted = adapted.replace(before, after)
    # Compiler options remain recorded in the raw output, without adding a
    # generic global variable to the application.
    adapted, count = re.subn(r'^const char \*GGC_OPTIONS = .*;\n', '', adapted,
                            flags=re.MULTILINE)
    if count != 1:
        raise RuntimeError("Unexpected IrGL compiler-options declaration")

    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    adapted = ("// Generated by tools/generate_galois.py; edit the IrGL source.\n"
               f"// Source SHA-256: {digest}\n#pragma once\n\n" + adapted + "\n")
    output = root / "kernels/generated/galois_generate_then_add.cuh"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(adapted)
    output.with_suffix(".raw.cu").write_text(raw)
    diff = difflib.unified_diff(raw.splitlines(True), adapted.splitlines(True),
                                fromfile="galois_generate_then_add.raw.cu", tofile=output.name)
    output.with_suffix(".adapter.diff").write_text("".join(
        line if line.endswith("\n") else line + "\n\\ No newline at end of file\n"
        for line in diff))
    print(output)


if __name__ == "__main__":
    main()
